    suspend fun readCsvTextFromUri(context: Context, uri: Uri): Result<String> =
        withContext(Dispatchers.IO) {
            try {
                val inputStream = context.contentResolver.openInputStream(uri)
                    ?: return@withContext Result.failure(IllegalArgumentException("Unable to open selected CSV file."))
                val text = BufferedReader(InputStreamReader(inputStream, StandardCharsets.UTF_8)).use { reader ->
                    reader.readText()
                }
                if (text.isBlank()) {
                    Result.failure(IllegalArgumentException("Selected CSV file is empty."))
                } else {
                    Result.success(text)
                }
            } catch (e: Exception) {
                Result.failure(e)
            }
        }

    fun parseCsvText(
        rawCsvText: String,
        sourceName: String = "Uploaded CSV",
        existingAssets: List<AssetEntity> = emptyList()
    ): CsvParsePreviewResult {
        val cleaned = rawCsvText.removePrefix("\uFEFF").trim()
        if (cleaned.isEmpty()) {
            return CsvParsePreviewResult(
                sourceName = sourceName,
                detectedDelimiter = ',',
                headers = emptyList(),
                totalDataRows = 0,
                validRows = emptyList(),
                rowErrors = listOf(CsvRowError(1, "", "CSV content is empty."))
            )
        }

        val delimiter = detectDelimiter(cleaned)
        val rawRows = parseRfc4180Rows(cleaned, delimiter)
            .filter { row -> row.any { it.isNotBlank() } }

        if (rawRows.isEmpty()) {
            return CsvParsePreviewResult(
                sourceName = sourceName,
                detectedDelimiter = delimiter,
                headers = emptyList(),
                totalDataRows = 0,
                validRows = emptyList(),
                rowErrors = listOf(CsvRowError(1, "", "No non-empty rows found in CSV."))
            )
        }

        val firstRow = rawRows.first()
        val hasHeaderRow = looksLikeHeaderRow(firstRow)
        val headers = if (hasHeaderRow) {
            firstRow.map { it.trim() }
        } else {
            TEMPLATE_HEADERS
        }
        val dataRows = if (hasHeaderRow) rawRows.drop(1) else rawRows

        val headerIndexMap = buildHeaderMap(headers)
        val existingById = existingAssets.associateBy { it.id.uppercase(Locale.US) }

        // Track IDs allocated during this batch so auto-generated IDs never collide
        val allocatedIds = existingById.keys.toMutableSet()
        var nextSr = (existingAssets.maxOfOrNull { it.sr } ?: existingAssets.size) + 1
        val nowMs = System.currentTimeMillis()

        val validRows = mutableListOf<ParsedCsvAssetRow>()
        val rowErrors = mutableListOf<CsvRowError>()
        val seenIdsInFile = mutableSetOf<String>()

        dataRows.forEachIndexed { idx, cells ->
            val lineNumber = if (hasHeaderRow) idx + 2 else idx + 1

            fun cellValue(canonicalKey: String): String {
                val colIdx = headerIndexMap[canonicalKey] ?: return ""
                return cells.getOrNull(colIdx)?.trim() ?: ""
            }

            val rawId = cellValue("id").uppercase(Locale.US)
            val rawName = cellValue("name")
            val rawSystem = cellValue("system")
            val rawCategory = cellValue("category")
            val rawLocation = cellValue("location")
            val rawBuilding = cellValue("building")
            val rawRoom = cellValue("room")
            val rawStatus = cellValue("status")
            val rawCriticality = cellValue("criticality")

            if (rawName.isBlank() && rawId.isBlank() && rawLocation.isBlank()) {
                return@forEachIndexed
            }

            if (rawName.isBlank()) {
                rowErrors.add(
                    CsvRowError(
                        rowNumber = lineNumber,
                        rawIdentifier = rawId.ifBlank { "Row $lineNumber" },
                        message = "Missing required 'Name' / 'Description' column value."
                    )
                )
                return@forEachIndexed
            }

            val resolvedSystem = normalizeSystem(rawSystem.ifBlank { rawCategory }, rawId)
            val isAutoId: Boolean
            val resolvedId: String = if (rawId.isBlank()) {
                isAutoId = true
                generateNextUniqueAssetId(resolvedSystem, allocatedIds)
            } else {
                isAutoId = false
                normalizeOrValidateAssetId(rawId, resolvedSystem, allocatedIds)
            }

            if (resolvedId.isEmpty()) {
                rowErrors.add(
                    CsvRowError(
                        rowNumber = lineNumber,
                        rawIdentifier = rawId,
                        message = "Invalid Asset ID '$rawId'. Expected AKA-HYD-XXX-000 or valid alphanumeric code."
                    )
                )
                return@forEachIndexed
            }

            if (!seenIdsInFile.add(resolvedId)) {
                rowErrors.add(
                    CsvRowError(
                        rowNumber = lineNumber,
                        rawIdentifier = resolvedId,
                        message = "Duplicate Asset ID '$resolvedId' appears multiple times in the same CSV file."
                    )
                )
                return@forEachIndexed
            }

            allocatedIds.add(resolvedId)

            val existingAsset = existingById[resolvedId]
            val catCode = resolvedId.split("-").getOrNull(2)
                ?: SopConstants.SYSTEM_CODES[resolvedSystem]
                ?: "GEN"

            val resolvedStatus = normalizeStatus(rawStatus, existingAsset?.status ?: "In service")
            val resolvedCriticality = normalizeCriticality(rawCriticality, existingAsset?.criticality ?: "Medium")

            val combinedLocation = when {
                rawLocation.isNotBlank() -> rawLocation
                rawBuilding.isNotBlank() && rawRoom.isNotBlank() -> "$rawBuilding · $rawRoom"
                rawBuilding.isNotBlank() -> rawBuilding
                existingAsset != null -> existingAsset.location
                else -> "Main Campus"
            }

            val parsedSr = cellValue("sr").toIntOrNull()
                ?: existingAsset?.sr
                ?: (nextSr++)

            val parsedQty = cellValue("quantity").toIntOrNull()?.coerceAtLeast(1)
                ?: existingAsset?.quantity
                ?: 1

            val parsedPurchaseYear = cellValue("purchaseYear").toIntOrNull()
                ?.takeIf { it in 1980..2035 }
                ?: existingAsset?.purchaseYear
                ?: 2022

            val parsedLifecycleYears = cellValue("lifeCycleYears").toIntOrNull()
                ?.takeIf { it in 1..60 }
                ?: existingAsset?.lifeCycleYears
                ?: 15

            val defaultRoutine = existingAsset?.routine
                ?: "D: Visual inspection, indicator status, abnormal noise/heat check | W: Cleaning, terminal/connection check, functional test | M: Full operational parameter log and safety interlock verification"
            val defaultPpm = existingAsset?.ppm
                ?: "Q: Comprehensive preventive maintenance, calibration & wear inspection | A: Annual overhaul, statutory testing & certification"
            val defaultStrategy = existingAsset?.strategy
                ?: "Preventive + Condition-Based (SOP-AKA-HYD-001)"

            val entity = (existingAsset ?: AssetEntity(
                id = resolvedId,
                name = rawName,
                system = resolvedSystem
            )).copy(
                id = resolvedId,
                sr = parsedSr,
                cat = cellValue("cat").ifBlank { catCode },
                name = rawName,
                system = resolvedSystem,
                category = rawCategory.ifBlank { resolvedSystem },
                criticality = resolvedCriticality,
                status = resolvedStatus,
                buildingName = rawBuilding.ifBlank { existingAsset?.buildingName ?: "" },
                location = combinedLocation,
                roomNo = rawRoom.ifBlank { existingAsset?.roomNo ?: "" },
                make = cellValue("make").ifBlank { existingAsset?.make ?: "" },
                model = cellValue("model").ifBlank { existingAsset?.model ?: "" },
                serial = cellValue("serial").ifBlank { existingAsset?.serial ?: "" },
                assetTag = cellValue("assetTag").ifBlank { existingAsset?.assetTag ?: "" },
                capacity = cellValue("capacity").ifBlank { existingAsset?.capacity ?: "" },
                quantity = parsedQty,
                purchaseYear = parsedPurchaseYear,
                lifeCycleYears = parsedLifecycleYears,
                installed = cellValue("installed").ifBlank { existingAsset?.installed ?: "" },
                amcVendor = cellValue("amcVendor").ifBlank { existingAsset?.amcVendor ?: "" },
                amcExpiry = cellValue("amcExpiry").ifBlank { existingAsset?.amcExpiry ?: "" },
                owner = cellValue("owner").ifBlank { existingAsset?.owner ?: "Facilities / MEP" },
                notes = cellValue("notes").ifBlank { existingAsset?.notes ?: "" },
                strategy = cellValue("strategy").ifBlank { defaultStrategy },
                routine = cellValue("routine").ifBlank { defaultRoutine },
                ppm = cellValue("ppm").ifBlank { defaultPpm },
                rev = (existingAsset?.rev ?: 0) + 1,
                lastUpdatedAt = nowMs,
                pendingOfflineSync = true
            )

            validRows.add(
                ParsedCsvAssetRow(
                    rowNumber = lineNumber,
                    asset = entity,
                    isAutoGeneratedId = isAutoId,
                    isExistingInDb = existingAsset != null
                )
            )
        }

        return CsvParsePreviewResult(
            sourceName = sourceName,
            detectedDelimiter = delimiter,
            headers = headers,
            totalDataRows = dataRows.size,
            validRows = validRows,
            rowErrors = rowErrors
        )
    }

    private fun detectDelimiter(text: String): Char {
        val firstLine = text.lineSequence().firstOrNull { it.isNotBlank() } ?: return ','
        var inQuotes = false
        var commaCount = 0
        var semicolonCount = 0
        var tabCount = 0
        for (ch in firstLine) {
            when {
                ch == '"' -> inQuotes = !inQuotes
                !inQuotes && ch == ',' -> commaCount++
                !inQuotes && ch == ';' -> semicolonCount++
                !inQuotes && ch == '\t' -> tabCount++
            }
        }
        return when {
            tabCount > commaCount && tabCount >= semicolonCount -> '\t'
            semicolonCount > commaCount -> ';'
            else -> ','
        }
    }

    fun parseRfc4180Rows(text: String, delimiter: Char = ','): List<List<String>> {
        val rows = mutableListOf<List<String>>()
        var currentRow = mutableListOf<String>()
        val currentCell = StringBuilder()
        var inQuotes = false
        var i = 0
        while (i < text.length) {
            val ch = text[i]
            if (inQuotes) {
                if (ch == '"') {
                    if (i + 1 < text.length && text[i + 1] == '"') {
                        currentCell.append('"')
                        i += 2
                        continue
                    } else {
                        inQuotes = false
                    }
                } else {
                    currentCell.append(ch)
                }
            } else {
                when (ch) {
                    '"' -> inQuotes = true
                    delimiter -> {
                        currentRow.add(currentCell.toString())
                        currentCell.clear()
                    }
                    '\r' -> {
                        currentRow.add(currentCell.toString())
                        currentCell.clear()
                        rows.add(currentRow)
                        currentRow = mutableListOf()
                        if (i + 1 < text.length && text[i + 1] == '\n') {
                            i++
                        }
                    }
                    '\n' -> {
                        currentRow.add(currentCell.toString())
                        currentCell.clear()
                        rows.add(currentRow)
                        currentRow = mutableListOf()
                    }
                    else -> currentCell.append(ch)
                }
            }
            i++
        }
        if (currentCell.isNotEmpty() || currentRow.isNotEmpty()) {
            currentRow.add(currentCell.toString())
            rows.add(currentRow)
        }
        return rows
    }

    private fun looksLikeHeaderRow(firstRow: List<String>): Boolean {
        val normalized = firstRow.map { normalizeHeaderToken(it) }
        val knownHeaderTokens = setOf(
            "assetid", "id", "name", "assetname", "description", "system",
            "location", "status", "maintenancestatus", "criticality", "make",
            "model", "serial", "capacity", "owner", "notes", "building", "room"
        )
        return normalized.count { it in knownHeaderTokens } >= 2
    }

    private fun normalizeHeaderToken(raw: String): String {
        return raw.lowercase(Locale.US).replace(Regex("[^a-z0-9]"), "")
    }

