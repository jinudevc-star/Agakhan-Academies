enum class CsvImportConflictMode(val label: String, val description: String) {
    UPSERT_MERGE(
        label = "Merge & Update Existing",
        description = "Insert new assets and update existing assets when Asset ID matches"
    ),
    INSERT_ONLY_SKIP_EXISTING(
        label = "Add New Only (Skip Duplicates)",
        description = "Only insert assets with new IDs; keep existing database records untouched"
    ),
    REPLACE_ALL(
        label = "Seed & Replace Entire Register",
        description = "Replace existing asset records with the uploaded CSV dataset"
    )
}

