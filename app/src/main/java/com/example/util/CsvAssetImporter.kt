                "cat", "catcode", "systemcode" -> "cat"
                "name", "assetname", "description", "equipmentname", "title", "asset", "item" -> "name"
                "system", "mepsystem", "discipline", "department", "systemcategory" -> "system"
                "category", "subcategory", "type", "assettype" -> "category"
                "criticality", "priority", "risk", "criticalitylevel" -> "criticality"
                "maintenancestatus", "status", "condition", "currentstatus", "operationalstatus", "state" -> "status"
                "location", "area", "site", "zone", "buildinglocation", "place" -> "location"
                "building", "buildingname", "block", "facility" -> "building"
                "room", "roomno", "roomnumber" -> "room"
                "make", "manufacturer", "brand", "oem" -> "make"
                "model", "modelno", "modelnumber" -> "model"
                "serial", "serialno", "serialnumber", "sn" -> "serial"
                "assettag", "tag", "tagno", "barcode" -> "assetTag"
                "capacity", "rating", "size", "power" -> "capacity"
                "quantity", "qty", "count", "units" -> "quantity"
                "purchaseyear", "yearofpurchase", "acquisitionyear", "year" -> "purchaseYear"
                "lifecycleyears", "lifecycle", "lifespan", "usefullife", "serviceyears" -> "lifeCycleYears"
                "installed", "installeddate", "installationdate", "commissioned" -> "installed"
                "amcvendor", "vendor", "serviceprovider", "contractor" -> "amcVendor"
                "amcexpiry", "contractexpiry", "warrantyexpiry", "expiry" -> "amcExpiry"
                "owner", "custodian", "responsible", "assignedto", "incharge" -> "owner"
                "strategy", "maintenancestrategy" -> "strategy"
                "routinechecks", "routine", "dailychecks", "soproutine" -> "routine"
                "ppm", "ppmschedule", "preventivemaintenance" -> "ppm"
                "notes", "note", "remarks", "comments", "observation" -> "notes"
                else -> null
            }
            if (canonical != null && !map.containsKey(canonical)) {
                map[canonical] = index
            }
        }
        return map
    }

    fun normalizeSystem(rawSystem: String, rawId: String = ""): String {
        val clean = rawSystem.trim()
        // Check exact match first
        SopConstants.SYSTEMS.firstOrNull { it.equals(clean, ignoreCase = true) }?.let { return it }

        val lower = clean.lowercase(Locale.US)
        when {
            lower.contains("elec") || lower.contains("power") || lower.contains("ups") ||
                lower.contains("dg") || lower.contains("solar") || lower.contains("transformer") ->
                return "Electrical"
            lower.contains("hvac") || lower.contains("air") || lower.contains("ac") ||
                lower.contains("chill") || lower.contains("vent") || lower.contains("fan") ->
                return "HVAC"
            lower.contains("plumb") || lower.contains("water") || lower.contains("ro") ||
                lower.contains("stp") || lower.contains("pump") || lower.contains("sewage") ->
                return "Plumbing & Water"
            lower.contains("fire") || lower.contains("safety") || lower.contains("hydrant") ||
                lower.contains("alarm") || lower.contains("extinguisher") ->
                return "Fire & Life Safety"
            lower.contains("kitch") || lower.contains("culin") || lower.contains("cold") ||
                lower.contains("oven") || lower.contains("dish") || lower.contains("dining") ->
                return "Kitchen & Culinary"
            lower.contains("lift") || lower.contains("elev") || lower.contains("trans") ||
                lower.contains("util") || lower.contains("lpg") || lower.contains("gas") ->
                return "Vertical Transport & Utility"
            lower.contains("civil") || lower.contains("fabric") || lower.contains("build") ||
                lower.contains("roof") || lower.contains("door") || lower.contains("furn") ->
                return "Civil & Building Fabric"
            lower.contains("pool") || lower.contains("athl") || lower.contains("sport") ||
                lower.contains("swim") || lower.contains("gym") ->
                return "Athletic & Pool"
        }

        // Infer from Asset ID code if present
        val idParts = rawId.uppercase(Locale.US).split("-")
        val codePart = idParts.getOrNull(2) ?: ""
        return when (codePart) {
            "ELE" -> "Electrical"
            "HVC" -> "HVAC"
            "WAT" -> "Plumbing & Water"
            "FIR" -> "Fire & Life Safety"
            "KIT" -> "Kitchen & Culinary"
            "UTL" -> "Vertical Transport & Utility"
            "CIV" -> "Civil & Building Fabric"
            "POL" -> "Athletic & Pool"
            else -> "Electrical"
        }
    }

    fun normalizeStatus(rawStatus: String, fallback: String = "In service"): String {
        val clean = rawStatus.trim()
        if (clean.isEmpty()) return fallback
        SopConstants.STATUS_OPTIONS.firstOrNull { it.equals(clean, ignoreCase = true) }?.let { return it }

        val lower = clean.lowercase(Locale.US)
        return when {
            lower.contains("operational") || lower.contains("in service") ||
                lower.contains("active") || lower.contains("working") ||
                lower == "ok" || lower == "good" || lower.contains("healthy") -> "In service"
            lower.contains("maintenance") || lower.contains("attention") ||
                lower.contains("warn") || lower.contains("repair") ||
                lower.contains("due") || lower.contains("degraded") -> "Needs attention"
            lower.contains("out of service") || lower.contains("down") ||
                lower.contains("fault") || lower.contains("broken") ||
                lower.contains("failed") || lower.contains("offline") ||
                lower.contains("decommission") -> "Out of service"
            lower.contains("standby") || lower.contains("season") ||
                lower.contains("spare") || lower.contains("idle") -> "Standby / seasonal"
            else -> fallback
        }
    }

    fun normalizeCriticality(rawCriticality: String, fallback: String = "Medium"): String {
        val clean = rawCriticality.trim()
        if (clean.isEmpty()) return fallback
        SopConstants.CRITICALITY_OPTIONS.firstOrNull { it.equals(clean, ignoreCase = true) }?.let { return it }

        val lower = clean.lowercase(Locale.US)
        return when {
            lower.startsWith("crit") || lower.startsWith("high") || lower == "p1" || lower == "1" -> "Critical"
            lower.startsWith("med") || lower.startsWith("norm") || lower == "p2" || lower == "2" -> "Medium"
            lower.startsWith("low") || lower.startsWith("min") || lower == "p3" || lower == "3" -> "Low"
            else -> fallback
        }
    }

    private fun generateNextUniqueAssetId(system: String, allocatedIds: Set<String>): String {
        val sysCode = SopConstants.SYSTEM_CODES[system] ?: "GEN"
        val prefix = "AKA-HYD-$sysCode-"
        var maxNum = allocatedIds
            .mapNotNull { id ->
                if (id.startsWith(prefix)) id.removePrefix(prefix).toIntOrNull() else null
            }
            .maxOrNull() ?: 0
        var candidate: String
        do {
            maxNum++
            candidate = "$prefix${maxNum.toString().padStart(3, '0')}"
        } while (candidate in allocatedIds)
        return candidate
    }

    private fun normalizeOrValidateAssetId(
        rawId: String,
        system: String,
        allocatedIds: Set<String>
    ): String {
        val clean = rawId.trim().uppercase(Locale.US)
        if (SopConstants.EXACT_ASSET_ID_REGEX.matches(clean)) {
            return clean
        }
        // If user supplied a numeric or short tag like "015" or "ELE-015", normalize into AKA-HYD-XXX-015
        val digitsOnly = clean.toIntOrNull()
        if (digitsOnly != null && digitsOnly in 1..99999) {
            val sysCode = SopConstants.SYSTEM_CODES[system] ?: "GEN"
            return "AKA-HYD-$sysCode-${digitsOnly.toString().padStart(3, '0')}"
        }
        val shortMatch = Regex("^([A-Z0-9]{2,4})-(\\d{1,5})$").find(clean)
        if (shortMatch != null) {
            val code = shortMatch.groupValues[1].padEnd(3, 'X').take(3)
            val num = shortMatch.groupValues[2].toInt().toString().padStart(3, '0')
            return "AKA-HYD-$code-$num"
        }
        // Accept any clean alphanumeric ID with dashes/underscores by converting or preserving if valid
        val safeChars = clean.replace(Regex("[^A-Z0-9-]"), "")
        if (safeChars.length >= 3) {
            val trailingDigits = Regex("(\\d+)$").find(safeChars)?.groupValues?.get(1)?.toIntOrNull()
            if (trailingDigits != null) {
                val sysCode = SopConstants.SYSTEM_CODES[system] ?: "GEN"
                val candidate = "AKA-HYD-$sysCode-${trailingDigits.toString().padStart(3, '0')}"
                if (candidate !in allocatedIds || safeChars == candidate) {
                    return candidate
                }
            }
            return safeChars
        }
        return ""
    }

    private fun escapeCsvCell(value: String): String {
        return if (value.contains(",") || value.contains("\"") || value.contains("\n") || value.contains("\r")) {
            "\"" + value.replace("\"", "\"\"") + "\""
        } else {
            value
        }
    }
